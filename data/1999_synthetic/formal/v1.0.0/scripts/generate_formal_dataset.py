def make_record(plan_row: dict, manifest: dict, attempt: int = 1) -> dict:
    label_id = plan_row["label_id"]
    family_id = plan_row["scenario_family_id"]
    code = CAT_CODES[label_id]
    seed_text = f"{plan_row['id']}:{attempt}:formal-v1.0.0"
    seed = int(hashlib.sha256(seed_text.encode()).hexdigest()[:16], 16)
    rng = random.Random(seed)
    scenes = SCENES[family_id]
    scene = scenes[(plan_row["family_ordinal"] - 1 + attempt - 1) % len(scenes)]
    condition, evidence, impact = scene
    loc = rng.choice(LOCATIONS[label_id])
    opener_index = rng.randrange(len(OPENING_FORMS))
    if plan_row["family_ordinal"] % 17 == 6:
        opening = rng.choice(SELF_CORRECT_OPENING_FORMS).format(loc=loc, condition=condition)
    else:
        opening = OPENING_FORMS[opener_index].format(loc=loc, condition=condition)

    turn_mod = (plan_row["family_ordinal"] + int(code.encode()[0]) + attempt) % 3
    question_count = [3, 4, 5][turn_mod]
    pattern_banks = {
        3: [
            ["WHEN", "IMPACT", "EXTENT"], ["DETAIL", "WHEN", "EVIDENCE"],
            ["IMPACT", "LOCATION", "COMPARE"], ["EXTENT", "EVIDENCE", "WHEN"],
            ["LOCATION", "DETAIL", "IMPACT"], ["EVIDENCE", "COMPARE", "EXTENT"],
        ],
        4: [
            ["WHEN", "DETAIL", "IMPACT", "EXTENT"], ["LOCATION", "WHEN", "EVIDENCE", "IMPACT"],
            ["IMPACT", "COMPARE", "DETAIL", "WHEN"], ["EXTENT", "EVIDENCE", "LOCATION", "COMPARE"],
            ["DETAIL", "IMPACT", "WHEN", "EVIDENCE"], ["COMPARE", "LOCATION", "EXTENT", "IMPACT"],
        ],
        5: [
            ["WHEN", "LOCATION", "DETAIL", "IMPACT", "EXTENT"], ["EVIDENCE", "WHEN", "COMPARE", "IMPACT", "LOCATION"],
            ["IMPACT", "DETAIL", "EXTENT", "WHEN", "EVIDENCE"], ["LOCATION", "COMPARE", "EVIDENCE", "DETAIL", "IMPACT"],
            ["EXTENT", "WHEN", "IMPACT", "LOCATION", "COMPARE"], ["DETAIL", "EVIDENCE", "WHEN", "EXTENT", "IMPACT"],
        ],
    }
    if label_id == "waste_truck_service":
        available_dimensions = WASTE_DIMENSIONS[family_id]
        required_dimension = {
            "FAM-WASTE-MISSED-STOP": "OBSERVATION",
            "FAM-WASTE-ALLEY-ACCESS": "OBSERVATION",
            "FAM-WASTE-ROUTE-SEGMENT-OMISSION": "SCOPE",
            "FAM-WASTE-SHORT-DWELL": "OBSERVATION",
            "FAM-WASTE-ROUTE-ORDER-CHANGE": "SEQUENCE",
            "FAM-WASTE-WEEKEND-SCHEDULE": "SCHEDULE",
            "FAM-WASTE-HOLIDAY-SCHEDULE": "SCHEDULE",
            "FAM-WASTE-ACCESS-INTERRUPTION": "CONTEXT",
            "FAM-WASTE-COLLECTION-CUE-FAILURE": "OBSERVATION",
        }.get(family_id)
        dimensions = [required_dimension] if required_dimension else []
        remainder = [dim for dim in available_dimensions if dim not in dimensions]
        dimensions += rng.sample(remainder, question_count - len(dimensions))
    else:
        dimensions = rng.choice(pattern_banks[question_count])
    lines = [f"R:{rng.choice(OPENERS)}", f"L:{opening}"]
    transitions = rng.sample(R_TRANSITIONS, k=question_count)
    for qnum, dim in enumerate(dimensions):
        transition = transitions[qnum] if qnum else ""
        question = question_for(dim, family_id, label_id, rng)
        lines.append(f"R:{transition}{question}")
        lines.append(f"L:{line_for_response(dim, scene, loc, label_id, family_id, rng, plan_row['family_ordinal'])}")
    lines.append(f"R:{rng.choice(R_CLOSINGS)}")
    transcript = "\n".join(lines)

    return {
        "id": plan_row["id"],
        "transcript": transcript,
        "label_id": label_id,
        "label_name": plan_row["label_name"],
        "scenario_id": plan_row["scenario_id"],
        "scenario_family_id": family_id,
        "split": plan_row["split"],
        "is_synthetic": True,
        "speaker_map": SPEAKER_MAP,
        "generator_model": GENERATOR_MODEL,
        "prompt_version": PROMPT_VERSION,
        "review_status": "pending_manual_review",
    }


def build_plan(manifest: dict) -> list[dict]:
    plan = []
    counters = Counter()
    for category in manifest["categories"]:
        label_id = category["label_id"]
        if label_id not in CAT_CODES:
            raise ValueError(f"Unknown label_id {label_id}")
        family_ordinals = Counter()
        for family in category["families"]:
            for _ in range(family["planned_records"]):
                counters[label_id] += 1
                family_ordinals[family["scenario_family_id"]] += 1
                seq = counters[label_id]
                plan.append({
                    "id": f"TPE1999-FORMAL-{CAT_CODES[label_id]}-{seq:04d}",
                    "scenario_id": f"SCENARIO-FORMAL-{CAT_CODES[label_id]}-{seq:04d}",
                    "label_id": label_id,
                    "label_name": category["label_name"],
                    "scenario_family_id": family["scenario_family_id"],
                    "split": family["split"],
                    "family_ordinal": family_ordinals[family["scenario_family_id"]],
                    "batch": (len(plan) // 50) + 1,
                })
    if len(plan) != 1000 or any(counters[label] != 200 for label in CAT_CODES):
        raise ValueError(f"Bad planned record counts: {len(plan)} {counters}")
    if any(row["split"] == "pilot" for row in plan):
        raise ValueError("Pilot must not enter the formal plan")
    return plan


def validate_record(record: dict, plan: dict, all_label_names: list[str]) -> list[str]:
    errors = []
    if list(record.keys()) != REQUIRED_FIELDS:
        errors.append("field_order_or_set")
    for key in REQUIRED_FIELDS:
        if key not in record:
            errors.append(f"missing:{key}")
    if record.get("id") != plan["id"] or record.get("scenario_id") != plan["scenario_id"]:
        errors.append("id_mismatch")
    for key in ("label_id", "label_name", "scenario_family_id", "split"):
        if record.get(key) != plan.get(key):
            errors.append(f"mapping_mismatch:{key}")
    if record.get("split") not in {"train", "validation", "test"}:
        errors.append("invalid_split")
    if record.get("is_synthetic") is not True:
        errors.append("is_synthetic_not_true")
    if record.get("speaker_map") != SPEAKER_MAP:
        errors.append("speaker_map_mismatch")
    if record.get("review_status") != "pending_manual_review":
        errors.append("review_status_mismatch")
    lines = record.get("transcript", "").splitlines()
    if len(lines) not in {9, 11, 13}:
        errors.append(f"turn_count:{len(lines)}")
    if not lines or lines[0][:2] != "R:" or lines[-1][:2] != "R:":
        errors.append("dialogue_open_close_role")
    if any(not (line.startswith("R:") or line.startswith("L:")) for line in lines):
        errors.append("invalid_speaker_prefix")
    if any(line[:2] != ("R:" if i % 2 == 0 else "L:") for i, line in enumerate(lines)):
        errors.append("speaker_order")
    if cjk_count(record.get("transcript", "")) < 200:
        errors.append(f"cjk_chars:{cjk_count(record.get('transcript',''))}")
    transcript = record.get("transcript", "")
    if any(name and name in transcript for name in all_label_names):
        errors.append("classification_name_leak")
    if re.search(r"(?:09\d{8}|0[2-8]\d?[- ]?\d{6,8}|\d{1,4}\s*(?:號|巷|弄|樓|室))", transcript):
        errors.append("phone_or_numeric_address_pattern")
    if re.search(r"我叫|姓名|手機號碼|行動電話|聯絡電話|電話號碼|身分證|門牌|地址是", transcript):
        errors.append("personal_data_language")
    if re.search(r"會派人|保證|保證處理|已安排|已經處理|明天會|馬上處理|一定會", transcript):
        errors.append("service_promise")
    return errors


def jsonl_bytes(records: list[dict]) -> bytes:
    return ("\n".join(json.dumps(r, ensure_ascii=False, separators=(",", ":")) for r in records) + "\n").encode("utf-8")


def write_if_new_or_same(path: Path, content: bytes) -> None:
    if path.exists():
        if path.read_bytes() != content:
            raise FileExistsError(f"Refusing to overwrite different output: {path}")
        return
    path.write_bytes(content)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--max-batches", type=int, default=20, help="Generate up to this many pending batches.")
    args = parser.parse_args()
    if args.max_batches < 1 or args.max_batches > 20:
        parser.error("--max-batches must be 1–20")
    if not MANIFEST_PATH.is_file() or not PILOT_PATH.is_file():
        raise FileNotFoundError("Frozen manifest or current Pilot is missing")
    manifest = yaml_to_json(MANIFEST_PATH)
    if manifest.get("status") != "frozen" or manifest.get("formal_dataset_target") != 1000:
        raise ValueError("Formal manifest is not frozen at the requested 1,000-record target")
    plan = build_plan(manifest)
    pilot_ids = {json.loads(line)["id"] for line in PILOT_PATH.read_text(encoding="utf-8").splitlines() if line.strip()}
    plan_ids = {row["id"] for row in plan}
    if len(plan_ids) != 1000 or plan_ids & pilot_ids:
        raise ValueError("Formal IDs collide or Pilot was mixed into the plan")

    raw_dir = OUT / "raw_generated"
    filtered_dir = OUT / "filtered_batches"
    filtered_all_dir = OUT / "filtered"
    raw_dir.mkdir(parents=True, exist_ok=True)
    filtered_dir.mkdir(parents=True, exist_ok=True)
    filtered_all_dir.mkdir(parents=True, exist_ok=True)
    checkpoint_path = OUT / "checkpoint.json"
    log_path = OUT / "batch_log.jsonl"
    if checkpoint_path.exists():
        checkpoint = json.loads(checkpoint_path.read_text(encoding="utf-8"))
    else:
        checkpoint = {"version": "formal-v1.0.0", "status": "in_progress", "completed_batches": [], "expected_batches": 20, "expected_records": 1000}
        checkpoint_path.write_text(json.dumps(checkpoint, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    # The row-level plan is written once and must remain identical on resume.
    plan_path = OUT / "generation_manifest.csv"
    plan_content = ["id,scenario_id,label_id,label_name,scenario_family_id,split,family_ordinal,batch\n"]
    plan_content.extend(
        ",".join(str(row[k]).replace(",", " ") for k in ["id", "scenario_id", "label_id", "label_name", "scenario_family_id", "split", "family_ordinal", "batch"]) + "\n"
        for row in plan
    )
    write_if_new_or_same(plan_path, "".join(plan_content).encode("utf-8"))

    plan_by_batch = defaultdict(list)
    for row in plan:
        plan_by_batch[row["batch"]].append(row)
    all_label_names = sorted({c["label_name"] for c in manifest["categories"]})
    done = set(checkpoint.get("completed_batches", []))
    new_completed = 0
    for batch_no in range(1, 21):
        if batch_no in done:
            continue
        if new_completed >= args.max_batches:
            break
        expected = plan_by_batch[batch_no]
        passed = False
        existing_attempts = [
            int(p.stem.rsplit("_", 1)[1])
            for p in raw_dir.glob(f"batch_{batch_no:03d}_attempt_*.jsonl")
        ]
        first_new_attempt = max(existing_attempts, default=0) + 1
        for attempt in range(first_new_attempt, first_new_attempt + 5):
            raw_path = raw_dir / f"batch_{batch_no:03d}_attempt_{attempt:03d}.jsonl"
            if raw_path.exists():
                continue
            candidates = [make_record(row, manifest, attempt) for row in expected]
            raw_bytes = jsonl_bytes(candidates)
            raw_path.write_bytes(raw_bytes)
            plan_lookup = {row["id"]: row for row in expected}
            errors_by_id = {r["id"]: validate_record(r, plan_lookup[r["id"]], all_label_names) for r in candidates}
            rejected = {rid: errors for rid, errors in errors_by_id.items() if errors}
            if rejected:
                log_row = {
                    "batch": batch_no, "attempt": attempt, "status": "rejected",
                    "records": len(candidates), "rejected_records": len(rejected),
                    "issues": rejected, "raw_file": str(raw_path.relative_to(OUT)),
                    "raw_sha256": hashlib.sha256(raw_bytes).hexdigest(),
                }
                with log_path.open("a", encoding="utf-8") as log:
                    log.write(json.dumps(log_row, ensure_ascii=False) + "\n")
                continue
            filtered_path = filtered_dir / f"batch_{batch_no:03d}.jsonl"
            filtered_bytes = jsonl_bytes(candidates)
            write_if_new_or_same(filtered_path, filtered_bytes)
            log_row = {
                "batch": batch_no, "attempt": attempt, "status": "accepted",
                "records": len(candidates), "rejected_records": 0,
                "label_counts": dict(Counter(r["label_id"] for r in candidates)),
                "split_counts": dict(Counter(r["split"] for r in candidates)),
                "raw_file": str(raw_path.relative_to(OUT)),
                "filtered_file": str(filtered_path.relative_to(OUT)),
                "raw_sha256": hashlib.sha256(raw_bytes).hexdigest(),
                "filtered_sha256": hashlib.sha256(filtered_bytes).hexdigest(),
            }
            with log_path.open("a", encoding="utf-8") as log:
                log.write(json.dumps(log_row, ensure_ascii=False) + "\n")
            passed = True
            break
        if not passed:
            checkpoint["status"] = "blocked_batch_validation"
            checkpoint["last_failed_batch"] = batch_no
            checkpoint["completed_batches"] = sorted(done)
            checkpoint["updated_at_utc"] = datetime.now(timezone.utc).isoformat()
            checkpoint_path.write_text(json.dumps(checkpoint, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
            raise RuntimeError(f"Batch {batch_no} failed after five attempts; inspect batch_log.jsonl")
        done.add(batch_no)
        new_completed += 1
        checkpoint["completed_batches"] = sorted(done)
        checkpoint["next_batch"] = next((n for n in range(1, 21) if n not in done), None)
        checkpoint["status"] = "complete" if len(done) == 20 else "in_progress"
        checkpoint["updated_at_utc"] = datetime.now(timezone.utc).isoformat()
        checkpoint_path.write_text(json.dumps(checkpoint, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print(f"batch {batch_no:03d}/020 accepted ({len(expected)} records)")

    if len(done) < 20:
        print(json.dumps({"status": checkpoint["status"], "completed_batches": len(done), "remaining_batches": 20-len(done)}, ensure_ascii=False))
        return 0

    accepted = []
    raw_records = []
    for n in range(1, 21):
        fpath = filtered_dir / f"batch_{n:03d}.jsonl"
        accepted.extend(json.loads(line) for line in fpath.read_text(encoding="utf-8").splitlines() if line.strip())
    for raw_path in sorted(raw_dir.glob("batch_*_attempt_*.jsonl")):
        raw_records.extend(json.loads(line) for line in raw_path.read_text(encoding="utf-8").splitlines() if line.strip())
    accepted_bytes = jsonl_bytes(accepted)
    raw_all_bytes = jsonl_bytes(raw_records)
    write_if_new_or_same(filtered_all_dir / "formal_filtered_v1.0.0.jsonl", accepted_bytes)
    write_if_new_or_same(OUT / "raw_generated" / "formal_raw_all_attempts_v1.0.0.jsonl", raw_all_bytes)

    final_jsonl_path = OUT / "formal_dataset_v1.0.0.jsonl"
    write_if_new_or_same(final_jsonl_path, accepted_bytes)
    csv_path = OUT / "formal_dataset_v1.0.0.csv"
    import io
    csv_buffer = io.StringIO(newline="")
    writer = csv.DictWriter(csv_buffer, fieldnames=REQUIRED_FIELDS, extrasaction="raise")
    writer.writeheader()
    writer.writerows(accepted)
    write_if_new_or_same(csv_path, csv_buffer.getvalue().encode("utf-8"))

    batch_summary_path = OUT / "batch_manifest.csv"
    batch_rows = []
    for n in range(1, 21):
        accepted_batch = [json.loads(line) for line in (filtered_dir / f"batch_{n:03d}.jsonl").read_text(encoding="utf-8").splitlines() if line.strip()]
        log_rows = [json.loads(line) for line in log_path.read_text(encoding="utf-8").splitlines() if line.strip()]
        accepted_log = [x for x in log_rows if x.get("batch") == n and x.get("status") == "accepted"][-1]
        batch_rows.append({
            "batch": f"{n:03d}", "records": len(accepted_batch),
            "label_counts": json.dumps(dict(Counter(r["label_id"] for r in accepted_batch)), ensure_ascii=False),
            "split_counts": json.dumps(dict(Counter(r["split"] for r in accepted_batch)), ensure_ascii=False),
            "filtered_sha256": accepted_log["filtered_sha256"],
        })
    with batch_summary_path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=["batch", "records", "label_counts", "split_counts", "filtered_sha256"])
        writer.writeheader(); writer.writerows(batch_rows)
    checkpoint["status"] = "complete"
    checkpoint["final_records"] = len(accepted)
    checkpoint["final_jsonl_sha256"] = hashlib.sha256(accepted_bytes).hexdigest()
    checkpoint["final_csv_sha256"] = hashlib.sha256(csv_path.read_bytes()).hexdigest()
    checkpoint["updated_at_utc"] = datetime.now(timezone.utc).isoformat()
    checkpoint_path.write_text(json.dumps(checkpoint, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"status": "complete", "records": len(accepted), "batches": 20, "jsonl": str(final_jsonl_path), "csv": str(csv_path)}, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
